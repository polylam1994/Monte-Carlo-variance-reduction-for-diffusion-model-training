"""Build a self-contained Kaggle *script* kernel (notebooks/<name>.py) that embeds this repo's
source code, runs a plan of training jobs on the available GPUs and packs the small result
files.  The script prints the SHA-256 of every file it writes so the code that ran on Kaggle
can be checked against the git commit (see results/sources.json).

python scripts/build_kaggle_script.py --plan configs/plans/cifar10_main.json \
       --out notebooks/cifar10_main.py --deadline 4000"""
import argparse
import hashlib
import os

FILES = ["src/mcvr/__init__.py", "src/mcvr/unet.py", "src/mcvr/diffusion.py", "src/mcvr/estimators.py",
         "src/mcvr/data.py", "src/mcvr/probes.py", "src/mcvr/train.py", "src/mcvr/fid.py",
         "scripts/run_queue.py"]

ap = argparse.ArgumentParser()
ap.add_argument("--plan", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--deadline", type=float, default=3600, help="no new job starts after this many seconds")
ap.add_argument("--configs", nargs="*", default=["configs/cifar10.yaml"])
a = ap.parse_args()

git = os.popen("git rev-parse --short HEAD").read().strip()
parts = ['"""Kaggle script kernel, auto-generated by scripts/build_kaggle_script.py. Do not edit by hand."""',
         "import hashlib, os, subprocess, sys, glob, shutil", "os.chdir('/kaggle/working')", "FILES = {}"]
for f in FILES + a.configs + [a.plan]:
    s = open(f).read()
    assert "'''" not in s and not s.endswith("\\"), f
    parts.append(f"FILES[{f!r}] = r'''{s}'''")
    print(f, hashlib.sha256(s.encode()).hexdigest()[:12])
parts.append(f'''
for f, s in FILES.items():
    os.makedirs(os.path.dirname(f) or ".", exist_ok=True)
    open(f, "w").write(s)
    print("wrote", f, hashlib.sha256(s.encode()).hexdigest()[:12])
def sh(c):
    print("$", c, flush=True); return subprocess.call(c, shell=True)
sh("nvidia-smi --query-gpu=name,memory.total --format=csv")
sh("pip install -q clean-fid==0.1.35 2>&1 | tail -1")
import torch, torchvision
print(sys.version, torch.__version__, torchvision.__version__, flush=True)
# resume support: results of an attached previous version are copied back
for d in glob.glob("/kaggle/input/*/results/raw/*/*"):
    dst = os.path.join("results", d.split("/results/", 1)[1])
    if not os.path.exists(dst):
        shutil.copytree(d, dst); print("restored", dst)
torchvision.datasets.CIFAR10("data/cifar10", train=True, download=True)  # once, before parallel jobs
torchvision.datasets.CIFAR10("data/cifar10", train=False, download=True)
ng = torch.cuda.device_count()
sh(f"python scripts/run_queue.py --plan {a.plan} --gpus {{','.join(map(str, range(ng)))}} --deadline {a.deadline} --extra git={git}")
sh("tail -n 4 logs/*.log")
sh("tar czf results_small.tgz --exclude='*.pt' results logs && ls -la results_small.tgz")
''')
os.makedirs(os.path.dirname(a.out), exist_ok=True)
open(a.out, "w").write("\n".join(parts))
print("wrote", a.out, os.path.getsize(a.out), "bytes; git", git)
