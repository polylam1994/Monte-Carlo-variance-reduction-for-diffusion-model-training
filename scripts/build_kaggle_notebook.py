"""Build a self-contained Kaggle notebook (.ipynb) that embeds this repo's source code,
runs a plan of training jobs on the available GPUs and packs the small result files.

python scripts/build_kaggle_notebook.py --plan configs/plans/cifar10_main.json \
       --out notebooks/cifar10_main.ipynb --deadline 4000
The notebook writes the code with %%writefile cells so it is readable on Kaggle."""
import argparse
import json
import os

FILES = ["src/mcvr/__init__.py", "src/mcvr/unet.py", "src/mcvr/diffusion.py", "src/mcvr/estimators.py",
         "src/mcvr/data.py", "src/mcvr/probes.py", "src/mcvr/train.py", "src/mcvr/fid.py",
         "scripts/run_queue.py"]

ap = argparse.ArgumentParser()
ap.add_argument("--plan", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--deadline", type=float, default=3600, help="no new job starts after this many seconds")
ap.add_argument("--configs", nargs="*", default=["configs/cifar10.yaml"])
ap.add_argument("--title", default="mcvr")
a = ap.parse_args()


def md(s):
    return {"cell_type": "markdown", "metadata": {}, "source": s}


def code(s):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": s}


git = os.popen("git rev-parse HEAD").read().strip()
cells = [md(f"# {a.title}\nAuto-generated by `scripts/build_kaggle_notebook.py` from commit `{git}` of "
            "Monte-Carlo-variance-reduction-for-diffusion-model-training. Do not edit by hand.")]
cells.append(code("%cd /kaggle/working\n!mkdir -p src/mcvr scripts configs/plans results/raw logs data\n"
                  "!nvidia-smi --query-gpu=name,memory.total --format=csv\n"
                  "!pip install -q clean-fid==0.1.35 2>&1 | tail -1\n"
                  "import torch, torchvision, sys; print(sys.version, torch.__version__, torchvision.__version__)"))
for f in FILES + a.configs + [a.plan]:
    cells.append(code(f"%%writefile {f}\n" + open(f).read()))
cells.append(code(
    "# Resume support: if a previous version of this notebook is attached as an input, copy its results\n"
    "import glob, shutil, os\n"
    "for d in glob.glob('/kaggle/input/*/results/raw/*/*'):\n"
    "    dst = d.split('/results/', 1)[1]; dst = os.path.join('results', dst)\n"
    "    if not os.path.exists(dst): shutil.copytree(d, dst); print('restored', dst)\n"))
cells.append(code(f"!echo '{{\"git\": \"{git}\"}}' > results/kaggle_git.json\n"
                  f"!python scripts/run_queue.py --plan {a.plan} --gpus $(python -c \"import torch;print(','.join(map(str,range(torch.cuda.device_count()))))\") "
                  f"--deadline {a.deadline} --extra git={git}"))
cells.append(code("!tail -n 5 logs/*.log\n"
                  "!tar czf results_small.tgz --exclude='*.pt' results logs && ls -la results_small.tgz"))
nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                   "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 5}
os.makedirs(os.path.dirname(a.out), exist_ok=True)
json.dump(nb, open(a.out, "w"), indent=1)
print("wrote", a.out, "cells:", len(cells))
